import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const html=readFileSync('index.html','utf8');
assert.match(html,/onclick="autoArrangeFurniture\(\)"/,'Automatic arrangement control must be visible.');
assert.match(html,/onclick="autoArrangeFurnitureByCategory\(\)"/,'Category arrangement control must be visible.');
assert.match(html,/function arrangeFurnitureItems\(items,successLabel\)/,'Shared arrangement routine must exist.');
const start=html.indexOf('function arrangeFurnitureItems(items,successLabel){');
assert.notEqual(start,-1,'Shared arrangement routine must exist.');
const end=html.indexOf('\nfunction autoArrangeFurniture(){',start);
assert.notEqual(end,-1,'Shared routine must end before public handlers.');
const fn=html.slice(start,end);
assert.match(fn,/querySelectorAll/,'Layout must operate on furniture elements through callers.');
assert.match(fn,/Math\.sqrt\(items\.length\*ratio\)/,'Grid must adapt to room aspect ratio.');
assert.match(fn,/offsetWidth/,'Arrangement must account for furniture width.');
assert.match(fn,/offsetHeight/,'Arrangement must account for furniture height.');
assert.match(fn,/Math\.max\(0,Math\.min\(/,'Furniture must stay within room bounds.');
assert.match(fn,/previous=items\.map/,'Original positions must be retained for rollback.');
assert.match(fn,/autoSaveRoom\(\)/,'Arrangement must use room history persistence.');
assert.match(fn,/previous\.forEach/,'Failed saves must restore original positions.');
assert.match(fn,/1つ戻す/,'User must be told that arrangement can be undone.');
assert.match(html,/function autoArrangeFurnitureByCategory\(\)/,'Category arrangement handler must exist.');
assert.match(html,/種類ごとにまとめて整列しました/,'Category arrangement must explain its result.');
assert.match(html,/arrangeFurnitureItems\(items,/,'Category arrangement must use the shared safe layout routine.');
console.log('Automatic and category-based furniture arrangement checks passed.');
